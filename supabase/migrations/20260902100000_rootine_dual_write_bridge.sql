create or replace function public.rootine_record_sync_reconciliation(
  p_domain text, p_entity text, p_entity_id text, p_revision bigint,
  p_client_source text, p_correlation_id text, p_diff_metadata jsonb
)
returns text language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); result_id text; safe_diff jsonb;
begin
  if uid is null then raise exception 'Authentication is required.' using errcode = '42501'; end if;
  if p_domain is null or p_entity is null or p_entity_id is null or p_revision is null or p_revision < 1
    or p_client_source not in ('web', 'ios', 'legacy', 'system') or p_correlation_id is null
    or p_diff_metadata is null then
    raise exception 'Invalid reconciliation metadata.' using errcode = '22023';
  end if;
  safe_diff := jsonb_build_object(
    'changed_paths', coalesce(p_diff_metadata->'changedPaths', p_diff_metadata->'changed_paths', '[]'::jsonb),
    'left_hash', coalesce(p_diff_metadata->'leftHash', p_diff_metadata->'left_hash'),
    'right_hash', coalesce(p_diff_metadata->'rightHash', p_diff_metadata->'right_hash'),
    'left_type', coalesce(p_diff_metadata->'leftType', p_diff_metadata->'left_type'),
    'right_type', coalesce(p_diff_metadata->'rightType', p_diff_metadata->'right_type'),
    'truncated', coalesce(p_diff_metadata->'truncated', false));
  insert into public.rootine_sync_reconciliation_log
    (user_id, storage_key, correlation_id, domain, entity, entity_id, revision,
     client_source, details, diff_metadata, status)
  values (uid, left(p_entity_id, 180), left(p_correlation_id, 180), left(p_domain, 80),
    left(p_entity, 80), left(p_entity_id, 180), p_revision, p_client_source,
    safe_diff, safe_diff, 'different') returning id into result_id;
  return result_id;
end;
$$;
revoke all on function public.rootine_record_sync_reconciliation(text, text, text, bigint, text, text, jsonb) from public;
grant execute on function public.rootine_record_sync_reconciliation(text, text, text, bigint, text, text, jsonb) to authenticated;

create or replace function public.rootine_get_dual_write_flags()
returns table (dual_write_enabled boolean, shadow_read_enabled boolean, observe_reconciliation boolean, reason text)
language sql security definer set search_path = public as $$
  select dual_write_enabled, shadow_read_enabled, observe_reconciliation, reason
  from public.rootine_sync_account_flags where user_id = auth.uid()
  union all select true, true, true, null::text where auth.uid() is not null
    and not exists (select 1 from public.rootine_sync_account_flags where user_id = auth.uid());
$$;
