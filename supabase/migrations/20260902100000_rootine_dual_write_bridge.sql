create or replace function public.rootine_set_dual_write_enabled(p_enabled boolean, p_reason text default null)
returns public.rootine_sync_account_flags
language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); result public.rootine_sync_account_flags;
begin
  if uid is null then raise exception 'Authentication is required.' using errcode = '42501'; end if;
  insert into public.rootine_sync_account_flags(user_id, dual_write_enabled, reason, updated_at)
  values (uid, coalesce(p_enabled, true), left(p_reason, 500), timezone('utc', now()))
  on conflict (user_id) do update set dual_write_enabled = excluded.dual_write_enabled,
    reason = excluded.reason, updated_at = excluded.updated_at returning * into result;
  return result;
end;
$$;
revoke all on function public.rootine_set_dual_write_enabled(boolean, text) from public;
grant execute on function public.rootine_set_dual_write_enabled(boolean, text) to authenticated;

